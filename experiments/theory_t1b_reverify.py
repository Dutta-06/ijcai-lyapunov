"""Re-verification of the stored interval-arithmetic covers (Part Q of theory_t1b.md) with the amended verifier of theory_t1b_rigorous.py (referee round T1b, findings 2, 5):
the hypotheses r > d_0, 'block critical point in D-hat', theta < v_# are asserted inside `verify`, the bootstrap test is the strict E_j < D_j/1.0001, and the guards that
replaced an undecided ball by 0 use an upper bound.  For each selected target of Part Q the cover is recomputed from the stored top exponent, with the 240 s
attempt budget by default (--budget), and compared with the stored row (balls, verify calls, widest ball, lowest exponent).  The two targets whose stored chain is incomplete (the ball-width and
time-budget stops) are not rerun: their outcome depends on the budget and the machine load.

Usage: python experiments/theory_t1b_reverify.py --run [--targets 0,1,...] | --from-raw      -> results/synthetic/theory_t1b_reverify.md (+ _raw.npz); environment TT1B_OUT.
"""
import argparse
import os
import sys
import time
import warnings

os.environ.setdefault('OMP_NUM_THREADS', '1')
import numpy as np

HERE = os.path.abspath(os.path.dirname(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, '..'))
import exp_theory_t1 as T      # noqa: E402
import theory_t1b_wide as W    # noqa: E402

OUT = os.environ.get('TT1B_OUT', os.path.join(HERE, '..', 'results', 'synthetic'))
RAW, MD = os.path.join(OUT, 'theory_t1b_reverify_raw.npz'), os.path.join(OUT, 'theory_t1b_reverify.md')
QRAW = os.path.join(os.environ.get('TT1B_Q', os.path.join(HERE, '..', 'results', 'synthetic')), 'theory_t1b_raw.npz')


def run(targets, budget):
    warnings.filterwarnings('ignore')
    Q = np.load(QRAW, allow_pickle=False)['Q_rows']
    rows = []
    for n_ in targets:
        K, sep, R, seed = T.C_TARGETS[W.Q_IDX[n_]]
        cs, As, c0 = T.make_target(K, sep, R, seed)
        prep = T.prepare(cs, As, c0)
        old = Q[n_]
        t0 = time.time()
        segs, complete, cur, calls = W.cover(prep, old[5], W.Q_BOT, budget=budget)
        wmax = max([w_[1] - w_[0] for w_ in segs]) if segs else 0.0
        rows.append(list(old[:11]) + [n_, len(segs), calls, wmax, cur, float(complete), time.time() - t0])
        print('reverify', n_, (K, sep, R, seed), rows[-1][11:], flush=True)
    return dict(RV_rows=np.array(rows, float), RV_budget=np.array([budget]))


BANNER = 'SUPERSEDED by results/synthetic/theory3n.md: the displacement accounting of the certificate was corrected (see review/REVIEW_roundT3AC.md, REVIEW_roundT3N.md); numbers below use the legacy accounting and are kept as history'


def report(raw):
    L = [BANNER + '\n', '# Re-verification of the stored interval covers with the amended verifier (generated by experiments/theory_t1b_reverify.py)\n',
         'Referee round T1b (findings 2 and 5).  `verify` now asserts r > d_0, the block critical point in D-hat and theta < v_#, tests E_j < D_j/1.0001 (strict), and uses the upper end of '
         'a ball where it used to substitute 0 for an undecided one.  Each cover is recomputed from the stored top exponent (attempt budget %g s per target; the stored run used %g s) and compared with Part Q of theory_t1b.md.\n' % (raw['RV_budget'][0], W.Q_BUDGET),
         '| K | sep | R | seed | top (log10) | balls stored / new | verify calls stored / new | widest ball stored / new | lowest exponent stored / new | status stored / new | same |',
         '|---|---|---|---|---|---|---|---|---|---|---|']
    nsame = 0
    for r in raw['RV_rows']:
        same = (int(r[6]) == int(r[12]) and int(r[7]) == int(r[13]) and abs(r[8] - r[14]) < 5e-4 and abs(r[9] - r[15]) < 5e-3 and int(r[10] > 0) == int(r[16] > 0))
        nsame += int(same)
        st = lambda c: 'complete' if c > 0 else 'incomplete'
        L.append('| %d | %s | %g | %d | %+.2f | %d / %d | %d / %d | %.3f / %.3f | %+.2f / %+.2f | %s / %s | %s |' % (
            r[0], '%g' % r[1] if r[0] > 1 else '-', r[2], r[3], r[5], r[6], r[12], r[7], r[13], r[8], r[14], r[9], r[15], st(r[10]), st(r[16]), 'yes' if same else 'NO'))
    L.append('\n%d of %d reverified covers coincide with the stored row (tops, number of balls, verify calls, widest ball, lowest exponent, status).  Not rerun: the targets whose stored chain is '
             'incomplete (budget dependent).\n' % (nsame, len(raw['RV_rows'])))
    return '\n'.join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--run', action='store_true')
    ap.add_argument('--from-raw', action='store_true')
    ap.add_argument('--targets', default='0,1,2,3,4,5,6,8')
    ap.add_argument('--budget', type=float, default=W.Q_BUDGET)
    a = ap.parse_args(argv)
    os.makedirs(OUT, exist_ok=True)
    if a.run:
        raw = run([int(x) for x in a.targets.split(',')], a.budget)
        np.savez(RAW, **raw)
    else:
        z = np.load(RAW, allow_pickle=False)
        raw = {k: z[k] for k in z.files}
    with open(MD, 'w') as fh:
        fh.write(report(raw))
    print('report written:', MD)


if __name__ == '__main__':
    main()
