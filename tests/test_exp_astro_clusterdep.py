    c = np.array([[40.3, 41.7]])
    assert np.allclose(P.phi(c), P0.phi(c)) and isinstance(P, IM.PixelPSF)
    fit = PG.fit_adequate(patch['psf'], rms_goal=0.0, k_max=3)
    assert fit['kind'] == 'general'
    Pg = C.make_kernel(patch, 3.0, fit)
    assert isinstance(Pg, PG.GeneralPixelPSF) and np.allclose(Pg.phi(c), PG.make_psf(fit, 100, 100, 3.0).phi(c))


