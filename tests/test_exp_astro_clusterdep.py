def test_a_tie_that_other_bootstrap_seeds_turn_into_a_loss_is_called_a_knife_edge(planted, monkeypatch):
    raw = planted['raw']
    real = E.verdicts_heldout
    ties = {k: (0.0, np.array([-0.01, 0.01]), 'tie') for k in real(raw, 'reg|')}
    monkeypatch.setattr(E, 'verdicts_heldout', lambda raw_, tname: dict(ties))
    def fake(raw_, tname, skip=(), seed=0):
        return {k: (0.0, np.array([-0.01, 0.01]), 'loss' if (seed % 3 == 0 and k == ('O2', 'ngcA')) else 'win' if (seed == 4 and k == ('O2f', 'ngcB')) else 'tie') for k in ties}
    monkeypatch.setattr(E, 'verdicts_subset', fake)
    md = '\n'.join(E.side_by_side_section(raw))
    assert 'A tie at seed 0 that other seeds turn into a win or a loss is a knife-edge, not a tie: O2 at ngcA: 0 of 30 seeds give a win, 10 a loss; O2f at ngcB: 1 of 30 seeds give a win, 0 a loss.' in md
    row = [ln for ln in md.splitlines() if ln.startswith('| O2 | ISS repaired minus crowdsource (front end) |')][0]
    assert row == '| O2 | ISS repaired minus crowdsource (front end) | 0 / 20 / 10 | 0 / 30 / 0 |'
    monkeypatch.setattr(E, 'verdicts_subset', lambda raw_, tname, skip=(), seed=0: dict(ties))
    assert 'knife-edge' not in '\n'.join(E.side_by_side_section(raw))


def fake_cluster_world(gap, cov_ell, other=None):
    """A spent-patch world of 5 clusters with one patch each: F(iso) - F(cs) = gap, every covariate constant except the stamp ellipticity (cov_ell) and `other` ({name: values})."""
    labels = ['M2', 'M53', 'M92', 'M3', 'M15']
    pks = ['P%d' % i for i in range(5)]
    raw = {}
    rng = np.random.default_rng(3)
    for i, pk in enumerate(pks):
        raw[pk + 'cs|tot'] = np.array([100.0, 40.0, 100.0, 40.0])
        raw[pk + 'iso|tot'] = np.array([100.0, 100 * (0.4 + gap[i]), 100.0, 100 * (0.4 + gap[i])])
        raw[pk + 'rule|tot'] = np.array([100.0, 100 * (0.4 + 0.5 * gap[i]), 100.0, 100 * (0.4 + 0.5 * gap[i])])
        for k in E.COVARIATES:
            raw[pk + 'cov|' + k] = np.array([float(rng.uniform(0, 1))])
        raw[pk + 'cov|stamp_ell'] = np.array([cov_ell[i]])
        for k, v in (other or {}).items():
            raw[pk + 'cov|' + k] = np.array([v[i]])
    return raw, pks, np.array(labels)


def test_loco_means_is_the_leave_one_cluster_out_linear_prediction_of_the_cluster_means():
    x, y = np.array([0.0, 1.0, 2.0, 3.0, 4.0]), np.array([1.0, 3.0, 5.0, 7.0, 9.0])
    rm, rn, signs, rho = E.loco_means(x, y)
    assert rm == pytest.approx(0.0, abs=1e-12) and rn > 1.0 and signs == 5 and rho == pytest.approx(1.0)
    rm2, rn2, signs2, rho2 = E.loco_means(x, y[::-1])
    assert rm2 == pytest.approx(0.0, abs=1e-12) and rho2 == pytest.approx(-1.0)
    rc, rnc, _, rhoc = E.loco_means(np.ones(5), y)                                                         # a constant covariate predicts the training mean
    assert rc == pytest.approx(rnc) and np.isnan(rhoc)
    assert rn == pytest.approx(np.sqrt(np.mean([(y[g] - np.delete(y, g).mean()) ** 2 for g in range(5)])))


def test_the_permutation_p_value_counts_the_assignments_of_the_cluster_gaps_that_do_as_well():
    gap = np.array([0.10, 0.04, -0.20, 0.0, 0.31])
    raw, pks, clusters = fake_cluster_world(gap, 2.0 * gap + 1.0)
    r = E.cluster_permutation(raw, pks, clusters, 'iso')
    assert r['best'] == 'stamp_ell' and r['n_perm'] == 120 and r['n_best'] == 1 and r['n_ell'] == 1
    assert r['obs']['stamp_ell'][0] == pytest.approx(0.0, abs=1e-12) and np.allclose(r['gap'], gap)
    raw2, pks2, cl2 = fake_cluster_world(gap, np.array([0.5, 0.5, 0.5, 0.5, 0.5]))                           # nothing is related: the p-value is about the best of random covariates
    r2 = E.cluster_permutation(raw2, pks2, cl2, 'iso')
    assert 1 <= r2['n_best'] <= 120 and r2['obs']['stamp_ell'][2] in range(6) and r2['n_ell'] == 120               # a constant covariate predicts the training mean for every assignment: every permutation does as well
    assert E.cluster_permutation(raw, pks[:4], clusters[:4], 'iso') is None


