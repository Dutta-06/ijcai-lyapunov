def faint_scene(seed, n=40, nst=14, fmin=150.0, fmax=900.0):
    rng = np.random.default_rng(seed)
    P0 = IM.PixelPSF(n, n, SIG)
    xy = rng.uniform(5, n - 5, (nst, 2))
    fl = 10 ** rng.uniform(np.log10(fmin), np.log10(fmax), nst)
    dn = P0.synth(xy, fl) + 120.0
    dn = dn + rng.normal(0, np.sqrt(dn / 4.6 + 1.0))
    return dict(dn=dn, psf=gauss_stamp(), gain=4.6, dark=1.0)


