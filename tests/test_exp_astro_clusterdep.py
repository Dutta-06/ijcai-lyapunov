# ---- the residual calibration (the first attempt at a repair; carried in the module and reported as a development result) ------------------------------

def planted_scene(seed=1, n=60, eps=0.0, inflate=1.0, hp=3.0):
    rng = np.random.default_rng(seed)
    P = IM.PixelPSF(n, n, SIG, hp=hp)
    xy = rng.uniform(6, n - 7, (12, 2))
    fl = 10.0 ** rng.uniform(2.5, 4.2, 12)
    gain, dark, sky = 4.6, 1.0, 150.0
    from scipy.ndimage import gaussian_filter
    P0 = IM.PixelPSF(n, n, SIG)
    clean = P0.synth(xy, fl) + sky
    var = clean / gain + dark
    wide = IM.PixelPSF(n, n, SIG * (1.0 + eps)).synth(xy, fl) + sky
    dn = wide + rng.normal(0, np.sqrt(var) * inflate)
    patch = dict(dn=dn, psf=gauss_stamp(), gain=gain, dark=dark)
    return patch, np.c_[xy, fl], P


def test_nominal_weights_are_the_frozen_weights_of_run_path():
    patch, det, P = planted_scene()
    from scipy.ndimage import gaussian_filter
    dn = patch['dn']
    expected = np.maximum(gaussian_filter(dn, 1.5, mode='reflect'), np.percentile(dn, 1))
    sw, var0, ex = C.nominal_weights(patch)
    assert np.allclose(sw, 1.0 / np.sqrt(expected / patch['gain'] + patch['dark'])) and np.allclose(var0, 1.0 / sw ** 2) and np.array_equal(ex, expected)


def test_make_kernel_is_the_frozen_isotropic_kernel_or_the_general_one():
    patch = fake_patch()
    sig, parts, _ = IM.fit_psf_parts(patch['psf'], n_parts=3, sigma0=1.0)
    P = C.make_kernel(patch, 3.0, None)
