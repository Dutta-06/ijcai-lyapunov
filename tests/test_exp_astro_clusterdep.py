def test_bright_split_counts_the_units_around_each_bright_star():
    t = planted_truth()
    fl = A.mag_to_counts
    det = np.array([[20.0, 20.0, fl(18.3)], [20.5, 20.3, fl(19.5)], [50.0, 20.0 + 0.3, fl(19.5)], [80.0, 80.0, fl(18.2)]])
    s = E.bright_split(det, t, mag_max=19.0)
    # the stars brighter than 19 mag: 18.0, 18.5 (50,... no: (20,50)), 18.2, 19.0 excluded (strict): 3 stars
    assert s[0] == 3
    assert s[1] == pytest.approx((2 + 0 + 1) / 3.0)                                                              # (20,20): two units within 1.5 px; (20,50): none; (80,80): one
    assert s[2] == pytest.approx(2.0 / 3.0) and s[4] == pytest.approx(2.0 / 3.0)                                 # a unit within 0.5 px for (20,20) and (80,80); matched: both
    assert E.bright_split(np.zeros((0, 3)), t)[1] != E.bright_split(np.zeros((0, 3)), t)[1]                     # nan for an empty catalogue


def test_recall_bin_and_f_of():
    t = planted_truth()
    fl = A.mag_to_counts
    det = np.array([[20.0, 20.0, fl(18.0)], [50.0, 80.0, fl(20.5)], [80.0, 50.0, fl(21.5)]])
