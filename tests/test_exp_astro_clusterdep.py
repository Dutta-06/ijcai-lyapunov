def gauss_stamp(sigma=SIG, n=51):
    """A unit-sum pixel-integrated round Gaussian stamp."""
    P = IM.PixelPSF(n, n, sigma)
    return P.phi(np.array([[(n - 1) / 2.0, (n - 1) / 2.0]]))[:, 0].reshape(n, n)


def fake_patch(stamp=None, n=100):
    return dict(dn=np.zeros((n, n)), psf=gauss_stamp() if stamp is None else stamp, gain=4.6, dark=1.0)


# ---- the coherence table ---------------------------------------------------------------------------------------------------------------------------

@pytest.fixture(scope='module')
def table():
    fit = PG.fit_adequate(gauss_stamp())
    return fit, C.coherence_table(fake_patch(), fit)


def test_the_coherence_table_is_one_at_zero_offset_symmetric_and_decreasing(table):
    fit, (off, tab) = table
    n = len(off)
    i0 = int(np.argmin(np.abs(off)))
    assert abs(tab[i0, i0] - 1.0) < 1e-12
    assert off[0] == -C.COH_GRID and abs(off[-1] - C.COH_GRID) < 1e-9 and abs(off[1] - off[0] - C.COH_STEP) < 1e-12
    assert np.allclose(tab, tab[::-1, ::-1], atol=1e-9) and np.allclose(tab, tab.T, atol=1e-9)           # (dx, dy) -> (-dx, -dy), and a round kernel
    row = tab[i0, i0:]
    assert np.all(np.diff(row) < 0) and row[-1] > 0


def test_the_coherence_of_a_round_gaussian_is_exp_minus_d2_over_4_sigma2(table):
    fit, (off, tab) = table
    i0 = int(np.argmin(np.abs(off)))
    for d in (1.0, 2.0, 3.0):
        j = int(np.argmin(np.abs(off - d)))
        assert abs(tab[i0, j] - np.exp(-d * d / (4 * SIG ** 2))) < 0.02
    assert abs(tab[i0, int(np.argmin(np.abs(off - 1.0)))] - tab[int(np.argmin(np.abs(off - 1.0))), i0]) < 1e-9


def test_the_coherence_of_a_wider_kernel_is_higher_at_the_same_offset():
    off, t1 = C.coherence_table(fake_patch(), PG.fit_adequate(gauss_stamp(1.0)))
    _, t2 = C.coherence_table(fake_patch(), PG.fit_adequate(gauss_stamp(1.6)))
    i0, j = int(np.argmin(np.abs(off))), int(np.argmin(np.abs(off - 1.5)))
    assert t2[i0, j] > t1[i0, j] + 0.1


def test_coherence_at_is_exact_on_the_grid_linear_between_and_zero_outside(table):
    fit, (off, tab) = table
    assert abs(C.coherence_at(off, tab, off[10], off[20]) - tab[20, 10]) < 1e-12                       # tab[iy, ix]: x is the column
    mid = C.coherence_at(off, tab, 0.5 * (off[10] + off[11]), off[20])
    assert abs(mid - 0.5 * (tab[20, 10] + tab[20, 11])) < 1e-12
    assert C.coherence_at(off, tab, 4.5, 0.0) == 0.0 and C.coherence_at(off, tab, 0.0, -4.5) == 0.0
    v = C.coherence_at(off, tab, np.array([0.0, 1.0]), np.array([0.0, 0.0]))
    assert v.shape == (2,) and v[0] > v[1]


# ---- the merge ---------------------------------------------------------------------------------------------------------------------------------------

def rho_at(table, d):
    fit, (off, tab) = table
    return float(C.coherence_at(off, tab, d, 0.0))


def test_two_units_closer_than_the_threshold_merge_into_the_flux_weighted_centroid(table):
    fit, (off, tab) = table
    det = np.array([[10.0, 10.0, 300.0], [10.8, 10.0, 100.0]])
    r = rho_at(table, 0.8)
    out, nm = C.merge_coherent(det, off, tab, r - 1e-6)
    assert nm == 1 and out.shape == (1, 3)
    assert abs(out[0, 2] - 400.0) < 1e-9 and abs(out[0, 0] - 10.2) < 1e-9 and abs(out[0, 1] - 10.0) < 1e-12
    out2, nm2 = C.merge_coherent(det, off, tab, r + 1e-6)
    assert nm2 == 0 and np.array_equal(out2, det)


def test_the_threshold_is_inclusive_and_the_input_is_not_modified(table):
    fit, (off, tab) = table
    det = np.array([[5.0, 5.0, 10.0], [5.5, 5.0, 10.0]])
    keep = det.copy()
    r = float(C.coherence_at(off, tab, 0.5, 0.0))
    out, nm = C.merge_coherent(det, off, tab, r)
    assert nm == 1 and np.array_equal(det, keep)


def test_the_closest_pair_merges_first_and_the_merged_unit_is_compared_again(table):
    fit, (off, tab) = table
    # A at 0, B at 0.5 (closest to A), C at 1.4: A and B merge first (centroid 0.25, flux 2); the merged unit is then 1.15 from C
    det = np.array([[0.0, 0.0, 1.0], [0.5, 0.0, 1.0], [1.4, 0.0, 1.0]]) + np.array([20.0, 20.0, 0.0])
    r_ab, r_mc, r_bc = rho_at(table, 0.5), rho_at(table, 1.15), rho_at(table, 0.9)
    rho = 0.5 * (r_mc + r_bc)                                                                              # above the merged-unit-to-C coherence, below A-B and B-C
    assert r_ab > r_bc > rho > r_mc
    out, nm = C.merge_coherent(det, off, tab, rho)
    assert nm == 1 and len(out) == 2 and abs(out[0, 0] - 20.25) < 1e-9 and out[0, 2] == 2.0 and out[1, 0] == 21.4        # had B-C (0.9 px) gone first, A would have stayed alone
    out2, nm2 = C.merge_coherent(det, off, tab, r_mc - 1e-3)
    assert nm2 == 2 and len(out2) == 1 and abs(out2[0, 2] - 3.0) < 1e-12 and abs(out2[0, 0] - (20.0 + 1.9 / 3.0)) < 1e-9


def test_a_unit_of_non_positive_flux_adds_its_flux_but_not_its_position(table):
    fit, (off, tab) = table
    det = np.array([[8.0, 8.0, 50.0], [8.4, 8.0, -20.0]])
    out, nm = C.merge_coherent(det, off, tab, 0.5)
    assert nm == 1 and abs(out[0, 2] - 30.0) < 1e-12 and out[0, 0] == 8.0
    det = np.array([[8.0, 8.0, -20.0], [8.4, 8.0, 50.0]])
    out, nm = C.merge_coherent(det, off, tab, 0.5)
    assert abs(out[0, 2] - 30.0) < 1e-12 and out[0, 0] == 8.4


def test_empty_and_single_catalogues_and_far_units_are_left_alone(table):
    fit, (off, tab) = table
    assert C.merge_coherent(np.zeros((0, 3)), off, tab, 0.5)[0].shape == (0, 3)
    one = np.array([[1.0, 2.0, 3.0]])
    assert np.array_equal(C.merge_coherent(one, off, tab, 0.0)[0], one)
    far = np.array([[10.0, 10.0, 1.0], [10.0, 15.0, 1.0], [30.0, 30.0, 1.0]])
    out, nm = C.merge_coherent(far, off, tab, 1e-9)                                                         # (10, 10) and (10, 15) are 5 px apart: outside the +-4 px table, coherence 0
    assert nm == 0 and len(out) == 3
    near = np.array([[10.0, 10.0, 1.0], [10.0, 13.5, 1.0]])
    assert C.merge_coherent(near, off, tab, 1e-9)[1] == 1                                                    # 3.5 px: inside the table, coherence small but positive


def test_the_merge_is_deterministic_and_returns_the_survivors_in_input_order(table):
    fit, (off, tab) = table
    rng = np.random.default_rng(3)
    det = np.c_[rng.uniform(10, 40, (60, 2)), rng.uniform(1, 10, 60)]
    a, na = C.merge_coherent(det, off, tab, 0.7)
    b, nb = C.merge_coherent(det.copy(), off, tab, 0.7)
    assert na == nb > 0 and np.array_equal(a, b) and len(a) == 60 - na
    assert abs(a[:, 2].sum() - det[:, 2].sum()) < 1e-9
    xs = [np.flatnonzero(np.abs(det[:, 2] - f) < 1e-12) for f in det[:, 2][:3]]
    assert all(len(x) >= 1 for x in xs)


def test_a_catalogue_with_no_pair_above_the_threshold_is_unchanged(table):
    fit, (off, tab) = table
