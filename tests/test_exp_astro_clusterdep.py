def test_spearman_is_the_rank_correlation_with_average_ranks_and_nan_for_a_constant():
    assert E.spearman([1, 2, 3, 4], [10, 20, 30, 40]) == pytest.approx(1.0)
    assert E.spearman([1, 2, 3, 4], [4, 3, 2, 1]) == pytest.approx(-1.0)
    assert E.spearman([1, 2, 3, 4, 5], [1, 4, 9, 16, 25]) == pytest.approx(1.0)                                  # monotone, not linear
    assert E.spearman([1, 2, 2, 3], [1, 2, 3, 4]) == pytest.approx(np.corrcoef([1, 2.5, 2.5, 4], [1, 2, 3, 4])[0, 1])
    assert np.isnan(E.spearman([1, 1, 1], [1, 2, 3]))


def test_loco_predicts_a_planted_linear_gap_beats_the_null_and_counts_the_signs():
    rng = np.random.default_rng(0)
    groups = np.repeat(['a', 'b', 'c', 'd', 'e'], 4)
    x = rng.uniform(0, 1, 20)
    y = -0.3 + 0.8 * x + rng.normal(0, 0.01, 20)
    rm, rn, rs, sg = E.loco(x, y, groups)
    assert rm < 0.05 < rn and rs > 0.9 and sg == 5
    # an irrelevant covariate does not beat the null
    z = rng.uniform(0, 1, 20)
    rm2, rn2, rs2, sg2 = E.loco(z, y, groups)
    assert rm2 > rm and rn2 == rn
    # the leave-out is by group: the prediction of a group never uses its own patches (a group with a unique x value cannot be predicted from itself)
    y3 = np.where(groups == 'a', 5.0, 0.0)
    rm3, rn3, _, _ = E.loco(np.zeros(20), y3, groups)
    assert rn3 == pytest.approx(rm3) and rn3 > 1.0


def test_loco_with_a_constant_covariate_is_the_null():
    groups = np.array(['a', 'a', 'b', 'b', 'c', 'c'])
    y = np.array([0.1, 0.2, -0.1, 0.0, 0.3, 0.2])
    rm, rn, rs, sg = E.loco(np.ones(6), y, groups)
    assert rm == pytest.approx(rn)


