def scaled(t, f):
    """The totals t with the matched counts (entries 1 and 3) multiplied by f."""
    u = np.ones(len(t))
    u[[1, 3]] = f
    return t * u


def with_failed(raw, patches):
    """A copy of the planted held-out raw in which the corrected scoring of the given (cluster, patch) is a failure: no matched star under 'reg|' for the frozen ISS and the front-end crowdsource."""
    out = dict(raw)
    for c, p in patches:
        for r in ('rule', 'crowdsource (front end)'):
            t = out[E.hkey(c, p) + 'reg|' + r + '|tot'].copy()
            t[1] = 0.0
            t[3] = 0.0
            out[E.hkey(c, p) + 'reg|' + r + '|tot'] = t
    return out


