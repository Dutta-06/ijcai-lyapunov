def lumpy_stamp(n=51):
    yy, xx = np.mgrid[-25:26, -25:26]
    s = np.exp(-0.5 * ((xx / 1.7) ** 2 + (yy / 1.0) ** 2)) + 0.25 * np.exp(-0.5 * (((xx - 1.5) / 0.7) ** 2 + ((yy + 1) / 0.7) ** 2))
    return s / s.sum()


