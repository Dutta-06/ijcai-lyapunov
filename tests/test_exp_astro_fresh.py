def test_the_freeze_is_written_checked_and_refuses_any_difference(tmp_path, monkeypatch):
    rec = dict(config=dict(sigma_b=3.0), files={'a': 'x'}, frozen_code='abc', data_files={'d': 'y'}, shifts={'c|1,2': [0.1, 0.2]})
    monkeypatch.setattr(E, 'freeze_record', lambda: json.loads(json.dumps(rec)))
    path = str(tmp_path / 'freeze_fresh.json')
    with pytest.raises(RuntimeError, match='no freeze record'):
        E.check_freeze(path)
    E.write_freeze(path)
    assert E.check_freeze(path) == rec
    text = open(path).read()
    assert list(json.loads(text)) == sorted(rec) and text.endswith('}\n') and text.index('"config"') < text.index('"files"') < text.index('"shifts"')                   # keys sorted, one trailing newline
    stored = json.loads(text)
    for key in rec:                                                                                                    # a key missing from the stored record is a difference
        gone = {k: v for k, v in stored.items() if k != key}
        json.dump(gone, open(path, 'w'))
        with pytest.raises(RuntimeError, match=key):
            E.check_freeze(path)
    E.write_freeze(path)
    for key, val in (('frozen_code', 'abd'), ('files', {'a': 'z'}), ('data_files', {'d': 'w'}), ('shifts', {'c|1,2': [0.1, 0.3]})):
        changed = dict(rec)
        changed[key] = val
        monkeypatch.setattr(E, 'freeze_record', lambda changed=changed: json.loads(json.dumps(changed)))
