# ---- the declared bootstrap and the verdicts, recomputed independently; the declared readings on controlled raws ---------------------------------------------------

def own_boot(raw, plist_c, a, b, tname='', B=2000, seed=0):
    """dF = F(a) - F(b) of the patches pooled and its 95 % percentile interval, written out from the declaration: 20 x 20 px blocks, B resamples, seed 0, the blocks resampled WITHIN each patch, the same draws for a and b."""
    rng = np.random.default_rng(seed)
    ba = [raw[E.pre_of(c, p) + tname + a + '|blk22'] for c, p in plist_c]
    bb = [raw[E.pre_of(c, p) + tname + b + '|blk22'] for c, p in plist_c]
    draws = [rng.integers(0, len(x), size=(B, len(x))) for x in ba]

    def f(blocks_, picks):
        tot = sum(blk[d].sum(1) for blk, d in zip(blocks_, picks)) if picks is not None else sum(blk.sum(0) for blk in blocks_)
        comp, pur = tot[..., 1] / np.maximum(tot[..., 0], 1), tot[..., 3] / np.maximum(tot[..., 2], 1)
        return 2 * comp * pur / np.maximum(comp + pur, 1e-12)
    d0 = f(ba, None) - f(bb, None)
    dd = f(ba, draws) - f(bb, draws)
    return float(d0), np.percentile(dd, [2.5, 97.5])


