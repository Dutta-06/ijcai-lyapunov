# ---- an independent matcher on the stored rows -------------------------------------------------------------------------------------------------------

def own_match_count(det_xy, det_mag, tr_xy, tr_mag, dpos=0.5, dmag=0.5):
    """Size of a maximum one-to-one matching of detections to truth sources within dpos px and dmag mag, by augmenting paths (Kuhn's algorithm): not the assignment solver that `astro_common.match` uses."""
    if len(det_xy) == 0 or len(tr_xy) == 0:
        return 0
    d = np.hypot(det_xy[:, None, 0] - tr_xy[None, :, 0], det_xy[:, None, 1] - tr_xy[None, :, 1])
    ok = (d <= dpos) & (np.abs(det_mag[:, None] - tr_mag[None, :]) <= dmag)
    adj = [np.flatnonzero(ok[i]).tolist() for i in range(len(det_xy))]
    owner = {}

    def try_(i, seen):
        for j in adj[i]:
            if j in seen:
                continue
            seen.add(j)
            if j not in owner or try_(owner[j], seen):
                owner[j] = i
                return True
        return False
    sys.setrecursionlimit(10000)
    return sum(1 for i in range(len(det_xy)) if try_(i, set()))


def own_counts(det, truth, n=100):
    """(scored detections, their magnitudes, scored truth, their magnitudes, size of the maximum matching) by the benchmark's definition re-implemented: scored area 2.5 px from the edge, 0.5 px and 0.5 mag."""
    x, y, f = det[:, 0], det[:, 1], det[:, 2]
    with np.errstate(divide='ignore', invalid='ignore'):
        m = np.where(f > 0, 22.5 - 2.5 * np.log10(np.where(f > 0, f, 1.0) * 0.00546689), np.nan)
    lo, hi = 2.0, n - 3.0
    dk = np.isfinite(m) & (x >= lo) & (x <= hi) & (y >= lo) & (y <= hi)
    tk = (truth['x'] >= lo) & (truth['x'] <= hi) & (truth['y'] >= lo) & (truth['y'] <= hi)
    dxy, tx = np.c_[x[dk], y[dk]], np.c_[truth['x'][tk], truth['y'][tk]]
    dm, tm = m[dk], truth['mag'][tk]
    return dxy, dm, tx, tm, own_match_count(dxy, dm, tx, tm)


