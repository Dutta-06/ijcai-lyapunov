def test_choose_fresh_walks_the_order_drops_clusters_without_enough_patches_and_waits_for_the_ones_not_yet_built():
    ranked = [dict(cluster=c, passes=True) for c in ('a', 'b', 'c', 'd')]
    assert F.choose_fresh(ranked, {'a': 0, 'b': 1, 'c': 4, 'd': 3}) == (['c', 'd'], ['a', 'b'])
    assert F.choose_fresh(ranked, {'a': 4, 'b': 2, 'c': 9}) == (['a', 'b'], [])
    assert F.choose_fresh(ranked, {'a': 0}) == ([], ['a'])                                                          # b has not been built: the order cannot go on
    assert F.choose_fresh(ranked, {'a': 0, 'c': 4, 'd': 4}) == ([], ['a'])                                          # ... even if later clusters have been built
    with_fail = [dict(cluster='x', passes=False)] + ranked[:2] + [dict(cluster='y', passes=False)] + ranked[2:]
    assert F.choose_fresh(with_fail, {'x': 9, 'y': 9, 'a': 1, 'b': 5, 'c': 5, 'd': 5}) == (['b', 'c'], ['a'])      # a cluster that fails the rule is never taken, however many patches it has
    assert F.choose_fresh(ranked, {'a': 2, 'b': 2, 'c': 2, 'd': 2}) == (['a', 'b'], []) and F.choose_fresh([], {}) == ([], [])
    assert F.choose_fresh(ranked, {'a': 1}, rule=dict(F.RULE, min_patches=1)) == (['a'], [])


