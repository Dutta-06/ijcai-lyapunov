def _stamp(sx, sy, lump=0.0):
    yy, xx = np.mgrid[-25:26, -25:26]
    s = np.exp(-0.5 * ((xx / sx) ** 2 + (yy / sy) ** 2))
    if lump:
        s = s + lump * np.exp(-0.5 * (((xx - 1.5) / 0.7) ** 2 + ((yy + 1) / 0.7) ** 2))
    return s / s.sum()


def _planted_patch(rng, sx, sy, lump, n=9, gain=4.6, dark=1.0, sky=150.0):
    """A 100 x 100 DN image with n well separated bright stars (the stamp convolved exactly), its stamp, and the stars' pixel positions and magnitudes."""
    psf = _stamp(sx, sy, lump)
    pts = []
    while len(pts) < n:
        p = rng.uniform(14, 86, 2)
        if all(np.hypot(*(p - q)) > 14 for q in pts):
            pts.append(p)
    pts = np.array(pts)
    mag = rng.uniform(18.2, 20.3, n)
    ax = np.arange(-25, 26)
    spl = RectBivariateSpline(ax, ax, psf, kx=3, ky=3)
    img = np.full((100, 100), sky)
    for (x, y), f in zip(pts, A.mag_to_counts(mag)):
        x0, x1, y0, y1 = int(x) - 12, int(x) + 13, int(y) - 12, int(y) + 13
        img[y0:y1, x0:x1] += f * spl(np.arange(y0, y1) - y, np.arange(x0, x1) - x)
    return dict(dn=img + rng.normal(0, np.sqrt(img / gain + dark)), psf=psf, gain=gain, dark=dark), pts, mag


def _catalog(rng, pts, mag, miss, fake, jit):
    """(x, y, flux, number of real detections): the first detections sit on the stars, the last `fake` do not."""
    keep = rng.uniform(size=len(pts)) > miss
    xy = pts[keep] + rng.normal(0, jit, (keep.sum(), 2))
    fl = A.mag_to_counts(mag[keep] + rng.normal(0, 0.05, keep.sum()))
    fx = rng.uniform(5, 95, (fake, 2))
    return np.r_[xy[:, 0], fx[:, 0]], np.r_[xy[:, 1], fx[:, 1]], np.r_[fl, A.mag_to_counts(rng.uniform(20.0, 23.0, fake))], int(keep.sum())


QUALITY = {'photutils': (0.6, 6, 0.2), 'tuned_phot': (0.45, 5, 0.15), 'fe_phot': (0.4, 5, 0.12), 'crowdsource': (0.5, 8, 0.15), 'fe_cs': (0.2, 3, 0.08)}


SHIFTS = {'ngcA': [(0.3, -0.45)], 'ngcB': [(0.1, 0.0), (0.05, 0.1)]}


def write_world(root, spec, shifts=SHIFTS):
    """Writes the patches, the truth lists, the baseline catalogue file and the registry of the planted clusters in `root`; spec: {cluster: [(x0, y0, sx, sy, lump), ...]}. The truth of a patch lies `shifts[cluster]` pixels
    away from the stars (so that adding the shift to the truth recovers them), as an astrometric offset would: 0.54 px (0.3 in x, -0.45 in y: beyond the 0.5 px tolerance, and a wrong sign or an exchange of the components is visible) for ngcA, 0.1 px and 0.1 px for the patches of ngcB. Returns (registry dict, catalogue path, truth by patch)."""
    rng = np.random.default_rng(11)
    reg, cats, truths = {}, {'meta|photutils_tuned': np.array([TUNED['photutils']]), 'meta|crowdsource_tuned': np.array([TUNED['crowdsource']]),
                             'meta|photutils_fe': np.array([FE['photutils']]), 'meta|crowdsource_fe': np.array([FE['crowdsource']])}, {}
    for ci, (c, plist) in enumerate(spec.items()):
        tpx, tpy, tm = [], [], []
        for (x0, y0, sx, sy, lump), shift in zip(plist, shifts[c]):
            patch, pts, mag = _planted_patch(rng, sx, sy, lump)
            d = os.path.join(root, 'patch_r_00000%d_1_0001_x%d_y%d_100x100' % (ci, x0, y0))
            os.makedirs(d)
            np.savez(os.path.join(d, 'patch_arrays.npz'), dn=patch['dn'], electrons=patch['dn'] * patch['gain'], nmgy=patch['dn'], sky_dn=np.full((100, 100), 150.0), psf51=patch['psf'], psf25=patch['psf'][13:38, 13:38],
                     gain=patch['gain'], dark_variance=patch['dark'], x0=x0, y0=y0)
            json.dump(dict(x0=x0, y0=y0, psfield_skysig=5.0), open(os.path.join(d, 'meta.json'), 'w'))
            tpx.append(pts[:, 0] + x0 - shift[0])
            tpy.append(pts[:, 1] + y0 - shift[1])
            tm.append(mag)
            truths[(c, x0, y0)] = (pts, mag, patch)
            k = '%s|x%d_y%d|' % (c, x0, y0)
            for tag, q in (('photutils', 'photutils'), (TUNED['photutils'], 'tuned_phot'), (FE['photutils'], 'fe_phot'), ('crowdsource', 'crowdsource'), (FE['crowdsource'], 'fe_cs')):
                x, y, f, nreal = _catalog(rng, pts, mag, *QUALITY[q])
                cats.update({k + tag + '|x': x, k + tag + '|y': y, k + tag + '|flux': f})
                if tag == 'crowdsource':                                                      # the detections on the stars have S/N 10, the fake ones S/N 2: the tuned post-filter (S/N >= 5) removes the latter
                    cats.update({k + 'crowdsource|dflux': np.r_[f[:nreal] * 0.1, f[nreal:] * 0.5], k + 'crowdsource|qf': np.ones_like(f), k + 'crowdsource|fracflux': np.ones_like(f),
                                 k + 'crowdsource|spread': np.zeros_like(f), k + 'crowdsource|rchi2': np.ones_like(f)})
        np.savez(os.path.join(root, 'truth_%s.npz' % c), px=np.concatenate(tpx), py=np.concatenate(tpy), m606=np.concatenate(tm))
        reg[c] = dict(title='Planted cluster %s, run %d' % (c, ci), run=ci, camcol=1, field=1, patches=[[p[0], p[1]] for p in plist], root=root, prefix='patch_r_00000%d_1_0001' % ci, truth='truth_%s.npz' % c,
                      shifts=[list(sh) for sh in shifts[c]])
    base = os.path.join(root, 'cats.npz')
    np.savez(base, **cats)
    return reg, base, truths


